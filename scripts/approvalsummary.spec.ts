// The one-page approval summary (three-gates C5): a reviewer approves a chart from approval.md and answers its check questions.
import { test, beforeEach } from 'node:test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { makeRepo, sdlc, write, hook, ARCH_OK, IMPL_OK } from './testkit.ts'

let repo: string
beforeEach(() => { repo = makeRepo(); sdlc(repo, ['init']) })
const P = '.rig/product', S = `${P}/sprints/sprint-1`, PAGE = `${S}/approval.md`
const HUMAN = { env: { SDLC_HUMAN: '1' } }
const SECRET = 's3cr3t-expected-value-42'
const page = (): string => fs.readFileSync(path.join(repo, PAGE), 'utf8')
const summary = (): string => { const r = sdlc(repo, ['chart', 'summary', '1']); assert.equal(r.code, 0, r.stderr); return page() }
const questions = (): string[] => { summary(); return [...page().split('## Check questions')[1]!.matchAll(/^\d\. (.*)$/gm)].map(m => m[1]!) }

const PRD = '---\nsprint: 1\nengineers: 1\n---\n# Sprint 1\n\n## Functional requirements\n\n### FR-1: totals\n\n- AC-1.1: WHEN a total is shown THE SYSTEM SHALL round it to 2 places. (proposed at chart)\n- AC-1.2: WHEN a cart is empty THE SYSTEM SHALL show 0.\n\n## Non-functional requirements\n\n| id | requirement | target |\n|---|---|---|\n| NFR-1 | Response time | p95 under 200 ms |\n\n## Open questions\n- which currency?\n'
const LEDGER = '- AC-1.1 [rule, proposed] prd.md:8 "WHEN a total is shown THE SYSTEM SHALL round it to 2 places."\n- AC-1.2 [rule] prd.md:9 "WHEN a cart is empty THE SYSTEM SHALL show 0."\n- NFR-1 [rule] prd.md:14 "NFR-1 | Response time | p95 under 200 ms"\n'
const intent = (extra = ''): string => `---\nsprint: 1\nprd: [FR-1]\ndepends: []\nestimate_days: 1\nkind: boundary\n---\n# alpha\n\n## Interfaces\nContract: api/x.yaml\nExample: api/ex.json\n\n## Behaviours\n- B1 (FR-1, AC-1.1): rounds totals\n- B2 (FR-1, AC-1.2): shows zero${extra}\n\n## Open questions\nnone\n`
const CASES = '| ID | Req | Intent | B | Level | Data | Expected |\n| TC-1 | FR-1, AC-1.1 | alpha | B1 | unit | - | ok |\n| TC-2 | FR-1, AC-1.2 | alpha | B2 | unit | - | ok |\n'
const fixture = (): void => {
  write(repo, `${S}/prd.md`, PRD); write(repo, `${S}/source.md`, 'Round totals.\nEmpty carts show 0.\n'); write(repo, `${S}/requirements.md`, LEDGER)
  write(repo, `${S}/conversion.md`, '- AC-1.1 source.md:1 "Round totals."\n- AC-1.2 source.md:2 "Empty carts show 0."\n')
  write(repo, `${S}/coverage.md`, '- auth open\n- tax n/a by Pat — no tax in this sprint\n- hosting n/a — the agent decided\n')
  write(repo, `${S}/intents/alpha.md`, intent()); write(repo, `${S}/testplan/cases.md`, CASES)
  write(repo, `${S}/holdout/TC-1.holdout.test.js`, `test('x', () => assert.equal('${SECRET}', 1))\n`)
  write(repo, 'api/x.yaml', 'openapi: 3\n'); write(repo, 'api/ex.json', '{}\n')
  write(repo, `${P}/adr/0001-store.md`, '---\nsprint: 1\nstatus: proposed\n---\n# 0001 Use SQLite\n\n## Decision\n\nWe store carts in SQLite, one file per user. More words.\n')
  write(repo, `${S}/chart-review.md`, 'verdict: changes-needed\n## Findings\n- first problem → fixed (confirmed)\n- second problem\n- third problem\n')
  write(repo, `${S}/implementation-plan.md`, IMPL_OK(['alpha'])); write(repo, `${P}/architecture.md`, ARCH_OK(1, 'sprint: 1'))
}

test('the page has the five sections, one ledger row per requirement with its quote, source line, intent and case ids', () => {
  fixture()
  const text = summary()
  assert.deepEqual([...text.matchAll(/^## (.*)$/gm)].map(m => m[1]), ['Acceptance criteria', 'Supplied by the agent', 'Not covered', 'Decisions', 'Check questions'])
  assert.match(text, /^<!-- Generated by `chart summary 1`/)
  assert.match(text, /\| AC-1\.1 \| "WHEN a total is shown THE SYSTEM SHALL round it to 2 places\." prd\.md:8; source\.md:1 \| alpha \| TC-1 \| yes \|/)
  assert.match(text, /\| AC-1\.2 \| .*source\.md:2 \| alpha \| TC-2 \| no \|/)
  assert.match(text, /\| NFR-1 \| .* \| none \| none \| no \|/)
  assert.ok(text.split('\n').length < 150)
})

test('the hidden-case column is read from file names only: a holdout file is never opened', () => {
  fixture()
  const text = summary()
  assert.ok(!text.includes(SECRET))
  assert.match(text, /\| TC-1 \| yes \|/)
})

test('supplied by the agent reuses prd proposed; not covered lists open and n/a topics, open questions and findings not confirmed or waived', () => {
  fixture()
  assert.equal(sdlc(repo, ['waive', 'chart-1', '3', 'accepted as is', '--by', 'Pat'], HUMAN).code, 0)
  const text = summary()
  const proposed = sdlc(repo, ['prd', 'proposed', '1']).stdout.trim()
  assert.ok(text.includes(proposed), 'the prd proposed output is embedded as it is')
  const notCovered = text.split('## Not covered')[1]!.split('## Decisions')[0]!
  assert.match(notCovered, /auth: open/)
  assert.match(notCovered, /tax: n\/a by Pat — no tax in this sprint/)
  assert.match(notCovered, /hosting: n\/a — the agent decided/)
  assert.match(notCovered, /which currency\?/)
  assert.match(notCovered, /finding 2: second problem \(not confirmed\)/)
  assert.match(notCovered, /finding 3: third problem \(waived by Pat: accepted as is\)/)
  assert.doesNotMatch(notCovered, /first problem/)
})

test('decisions: one line per ADR (title and decision sentence) and every contract an intent names', () => {
  fixture()
  const d = summary().split('## Decisions')[1]!.split('## Check questions')[0]!
  assert.match(d, /- 0001 Use SQLite: We store carts in SQLite, one file per user\./)
  assert.doesNotMatch(d, /More words/)
  assert.match(d, /- alpha: contract api\/x\.yaml/)
})

test('check questions: proposed values first, then numeric NFRs, then contracts, at most 3', () => {
  fixture()
  assert.deepEqual(questions().map(q => q.split(' ')[0]), ['AC-1.1', 'NFR-1', 'alpha:'], 'one proposed row, then the NFR, then the contract')
  const first = questions()[0]!
  assert.match(first, /\(proposed at chart\)\. Is that what the client wants, and why\?$/)
  write(repo, `${S}/intents/alpha.md`, intent(' (proposed at chart)\n- B3 (FR-1): third (proposed at chart)'))
  write(repo, `${P}/adr/0001-store.md`, '---\nsprint: 1\nstatus: proposed\n---\n# 0001 Use SQLite\n\n## Decision\n\nWe store carts in SQLite (proposed at chart).\n')
  const q = questions()
  assert.equal(q.length, 3)
  assert.deepEqual(q.map(x => x.split(' ')[0]), ['AC-1.1', 'alpha#B2', 'alpha#B3'], 'proposed values fill the three slots, so the NFR and the contract wait')
})

test('a sprint with nothing to ask has no questions and says so', () => {
  fixture()
  write(repo, `${S}/requirements.md`, LEDGER.replace('[rule, proposed]', '[rule]').split('\n').slice(0, 2).join('\n') + '\n')
  write(repo, `${S}/intents/alpha.md`, intent().replace('kind: boundary', 'kind: internal').replace(/Contract: .*\nExample: .*\n/, ''))
  assert.deepEqual(questions(), [])
  assert.match(page(), /No check questions/)
})

test('a long ledger is truncated with a count', () => {
  fixture()
  write(repo, `${S}/requirements.md`, Array.from({ length: 60 }, (_, i) => `- AC-1.${i + 1} [rule] prd.md:9 "rule ${i + 1}"`).join('\n') + '\n')
  const text = summary()
  assert.match(text, /\.\.\. 20 more rows? \(see requirements\.md\)/)
  assert.ok(text.split('\n').length < 150)
})

// ---------- approving ----------
const cleanChart = (marked = true): void => {
  write(repo, `${S}/prd.md`, '---\nsprint: 1\nengineers: 1\n---\n# Sprint 1\n\n### FR-1: thing\n\n## Open questions\nnone\n')
  write(repo, `${S}/intents/alpha.md`, `---\nsprint: 1\nprd: [FR-1]\ndepends: []\nestimate_days: 1\nkind: internal\n---\n# i\n\n## Interfaces\nnone\n\n## Behaviours\n- B1 (FR-1): works${marked ? ' (proposed at chart)' : ''}\n\n## Open questions\nnone\n`)
  write(repo, `${P}/architecture.md`, ARCH_OK(1, 'sprint: 1')); write(repo, `${S}/implementation-plan.md`, IMPL_OK(['alpha']))
  write(repo, `${S}/chart-review.md`, 'verdict: pass\n## Findings\n## Deferred\n'); write(repo, `${S}/testplan/cases.md`, '| ID | Req | Intent | B | Level | Data | Expected |\n| TC-1 | FR-1 | alpha | B1 | unit | - | ok |\n')
}
const answersFile = (v: unknown): string => { const f = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'rig-answers-')), 'answers.json'); fs.writeFileSync(f, JSON.stringify(v)); return f }
const approve = (...a: string[]) => sdlc(repo, ['approve', 'chart-1', '--by', 'Pat', ...a], HUMAN)
const record = (): { answers: { question: string; answer: string }[]; files: { path: string }[] } => JSON.parse(fs.readFileSync(path.join(repo, `${S}/approval.json`), 'utf8'))

test('approve without answers regenerates the page, prints its path and the questions, and records nothing', () => {
  cleanChart()
  const r = approve()
  assert.equal(r.code, 1)
  assert.ok(fs.existsSync(path.join(repo, PAGE)))
  assert.match(r.stderr, /approval\.md/)
  assert.match(r.stderr, /1\. alpha#B1 .*\(proposed at chart\)/)
  assert.match(r.stderr, /--answers/)
  assert.ok(!fs.existsSync(path.join(repo, `${S}/approval.json`)))
})

test('approve refuses a blank, skip, n/a or short answer, naming the question, and a wrong count', () => {
  cleanChart(); const q1 = /1\. (alpha#B1)/
  for (const bad of ['', '   ', 'skip', 'Skip.', 'n/a', 'N/A', 'too short', 'ok']) {
    const r = approve('--answers', answersFile([bad]))
    assert.equal(r.code, 1, bad)
    assert.match(r.stderr, q1, `names the question for "${bad}"`)
  }
  assert.equal(approve('--answers', answersFile([])).code, 1)
  assert.equal(approve('--answers', answersFile(['a real answer here', 'extra answer here'])).code, 1)
  assert.equal(approve('--answers', path.join(os.tmpdir(), 'rig-no-such-answers.json')).code, 1)
  assert.ok(!fs.existsSync(path.join(repo, `${S}/approval.json`)))
})

test('approve accepts real answers and stores them beside who and when', () => {
  cleanChart()
  const r = approve('--answers', answersFile(['Yes: the client said works means works, in their words.']))
  assert.equal(r.code, 0, r.stderr)
  const rec = record() as unknown as { by: string; at: string; answers: { question: string; answer: string }[] }
  assert.equal(rec.by, 'Pat'); assert.ok(rec.at)
  assert.equal(rec.answers.length, 1)
  assert.match(rec.answers[0]!.question, /^alpha#B1 .*\(proposed at chart\)/)
  assert.equal(rec.answers[0]!.answer, 'Yes: the client said works means works, in their words.')
  assert.ok(record().files.some(f => f.path === PAGE), 'approval.md is one of the approved files')
})

test('a sprint with no questions approves without answers', () => {
  cleanChart(false)
  const r = approve()
  assert.equal(r.code, 0, r.stderr)
  assert.deepEqual(record().answers ?? [], [])
})

test('editing approval.md, or a file that feeds it, makes the approval stale', () => {
  cleanChart(); assert.equal(approve('--answers', answersFile(['A real answer, long enough.'])).code, 0)
  const state = (): string => (JSON.parse(sdlc(repo, ['ready', '--json']).stdout) as unknown[]).length ? 'ready' : 'blocked'
  assert.equal(state(), 'ready')
  fs.appendFileSync(path.join(repo, PAGE), 'edited by hand\n')
  assert.equal(state(), 'blocked')
  assert.match(sdlc(repo, ['chart', 'report', '1']).stdout, /chart-1: stale/)
})

test('approval.md is protected from the model\'s Write and Edit, and may still be read', () => {
  fixture()
  const denied = (tool: string, input: object): string | null => { const o = hook(repo, 'holdout-guard', { tool_name: tool, tool_input: input }).stdout; return o ? JSON.parse(o).hookSpecificOutput.permissionDecision : null }
  for (const tool of ['Write', 'Edit', 'MultiEdit']) assert.equal(denied(tool, { file_path: path.join(repo, PAGE) }), 'deny', tool)
  assert.equal(denied('Write', { file_path: path.join(repo, `${S}/prd.md`) }), null)
  assert.equal(denied('Read', { file_path: path.join(repo, PAGE) }), null)
})
