// ---------- approving ----------
const cleanChart = (marked = true): void => {
  write(repo, `${S}/prd.md`, '---\nsprint: 1\nengineers: 1\n---\n# Sprint 1\n\n### FR-1: thing\n\n## Open questions\nnone\n')
  write(repo, `${S}/intents/alpha.md`, `---\nsprint: 1\nprd: [FR-1]\ndepends: []\nestimate_days: 1\nkind: internal\n---\n# i\n\n## Interfaces\nnone\n\n## Behaviours\n- B1 (FR-1): works${marked ? ' (proposed at chart)' : ''}\n\n## Open questions\nnone\n`)
  write(repo, `${P}/architecture.md`, ARCH_OK(1, 'sprint: 1')); write(repo, `${S}/implementation-plan.md`, IMPL_OK(['alpha']))
  write(repo, `${S}/chart-review.md`, 'verdict: pass\n## Findings\n## Deferred\n'); write(repo, `${S}/testplan/cases.md`, '| ID | Req | Intent | B | Level | Data | Expected |\n| TC-1 | FR-1 | alpha | B1 | unit | - | ok |\n')
}
const approve = (...a: string[]) => sdlc(repo, ['approve', 'chart-1', '--by', 'Pat', ...a], HUMAN)
const record = (): { answers: { question: string; answer: string }[]; files: { path: string }[] } => JSON.parse(fs.readFileSync(path.join(repo, `${S}/approval.json`), 'utf8'))
const PENDING = `${S}/answers.pending.json`
const shaOf = (): string => /page sha ([0-9a-f]{64})/.exec(approve('--ask').stderr)![1]!
// What AskUserQuestion's PostToolUse hook sees: the questions with the page marker, and the person's answers keyed by question text.
const ask = (answers: string[], opts: { sha?: string; qs?: string[] } = {}) => {
  const qs = opts.qs ?? questions(), sha = opts.sha ?? shaOf()
  const asked = qs.map(q => `[page sha ${sha.slice(0, 12)}] ${q}`)
  return hook(repo, 'asked', { tool_name: 'AskUserQuestion', tool_input: { questions: asked.map(question => ({ question })) }, tool_response: { answers: Object.fromEntries(asked.map((q, i) => [q, answers[i]])) } })
}

test('approve without recorded answers regenerates the page, prints its path, sha and the questions, and records nothing', () => {
  cleanChart()
  const r = approve()
  assert.equal(r.code, 1)
  assert.ok(fs.existsSync(path.join(repo, PAGE)))
  assert.match(r.stderr, /approval\.md/)
  assert.match(r.stderr, /page sha [0-9a-f]{64}/)
  assert.match(r.stderr, /1\. alpha#B1 .*\(proposed at chart\)/)
  assert.match(r.stderr, /answer the questions through \/rig:approve/)
  assert.ok(!fs.existsSync(path.join(repo, `${S}/approval.json`)))
})

test('--ask never approves, even when the chart has only the fallback question', () => {
  cleanChart(false)
  const r = approve('--ask')
  assert.equal(r.code, 1)
  assert.match(r.stderr, /1\. Which acceptance criterion is riskiest/)
  assert.ok(!fs.existsSync(path.join(repo, `${S}/approval.json`)))
})

test('the hook, not the model, writes answers.pending.json from the AskUserQuestion response', () => {
  cleanChart()
  assert.equal(ask(['Yes: the client said works means works.']).code, 0)
  const rec = JSON.parse(fs.readFileSync(path.join(repo, PENDING), 'utf8'))
  assert.equal(rec.page_sha, shaOf()); assert.ok(rec.at)
  assert.match(rec.answers[0].question, /^alpha#B1 /)
  assert.equal(rec.answers[0].answer, 'Yes: the client said works means works.')
})

test('a batch that is not this chart\'s questions, or lacks the page marker, records nothing', () => {
  cleanChart()
  ask(['Yes: a real answer here.'], { qs: ['Which colour do you want?'] })
  ask(['Yes: a real answer here.'], { sha: 'f'.repeat(64) })
  assert.ok(!fs.existsSync(path.join(repo, PENDING)))
})

test('the model cannot write or edit answers.pending.json', () => {
  fixture()
  const denied = (tool: string): string | null => { const o = hook(repo, 'holdout-guard', { tool_name: tool, tool_input: { file_path: path.join(repo, PENDING) } }).stdout; return o ? JSON.parse(o).hookSpecificOutput.permissionDecision : null }
  for (const tool of ['Write', 'Edit', 'MultiEdit']) assert.equal(denied(tool), 'deny', tool)
})

test('approve refuses a blank, skip, n/a or short recorded answer, naming the question', () => {
  cleanChart()
  for (const bad of ['', '   ', 'skip', 'Skip.', 'n/a', 'N/A', 'too short', 'ok']) {
    ask([bad])
    const r = approve()
    assert.equal(r.code, 1, bad)
    assert.match(r.stderr, /1\. alpha#B1/, `names the question for "${bad}"`)
  }
  assert.ok(!fs.existsSync(path.join(repo, `${S}/approval.json`)))
})

test('approve refuses answers recorded for another page (an old file, or inputs edited between the two runs)', () => {
  cleanChart(); ask(['Yes: the client said works means works.'])
  write(repo, `${S}/intents/alpha.md`, fs.readFileSync(path.join(repo, `${S}/intents/alpha.md`), 'utf8').replace('works (proposed at chart)', 'works differently (proposed at chart)'))
  const r = approve()
  assert.equal(r.code, 1)
  assert.match(r.stderr, /another version of the page/)
  assert.ok(!fs.existsSync(path.join(repo, `${S}/approval.json`)))
})

test('approve refuses an answers file the model wrote itself (questions or sha that the page does not have)', () => {
  cleanChart(); questions()
  fs.writeFileSync(path.join(repo, PENDING), JSON.stringify({ page_sha: shaOf(), answers: [{ question: 'made up', answer: 'a long invented answer' }] }))
  const r = approve()
  assert.equal(r.code, 1)
  assert.match(r.stderr, /not for these questions/)
})

test('approve accepts recorded answers, stores them beside who and when, echoes each, and removes the pending file', () => {
  cleanChart()
  ask(['Yes: the client said works means works, in their words.'])
  const r = approve()
  assert.equal(r.code, 0, r.stderr)
  assert.match(r.stdout, /recorded answers:\n  alpha#B1 .* -> Yes: the client said works means works, in their words\./)
  const rec = record() as unknown as { by: string; at: string; answers: { question: string; answer: string }[] }
  assert.equal(rec.by, 'Pat'); assert.ok(rec.at)
  assert.equal(rec.answers.length, 1)
  assert.match(rec.answers[0]!.question, /^alpha#B1 .*\(proposed at chart\)/)
  assert.equal(rec.answers[0]!.answer, 'Yes: the client said works means works, in their words.')
  assert.ok(record().files.some(f => f.path === PAGE), 'approval.md is one of the approved files')
  assert.ok(!fs.existsSync(path.join(repo, PENDING)))
})

test('a sprint with nothing to ask is still asked the fallback question before it approves', () => {
  cleanChart(false)
  assert.equal(approve().code, 1)
  ask(['The login criterion; TC-1 proves it end to end.'])
  const r = approve()
  assert.equal(r.code, 0, r.stderr)
  assert.equal(record().answers.length, 1)
})

test('chart summary on an approved chart prints the page and leaves the file alone', () => {
  cleanChart(); ask(['Yes: the client said works means works.']); assert.equal(approve().code, 0)
  const before = page()
  fs.utimesSync(path.join(repo, PAGE), new Date(0), new Date(0))
  const r = sdlc(repo, ['chart', 'summary', '1'])
  assert.equal(r.code, 0); assert.match(r.stdout, /^<!-- Generated /)
  assert.equal(page(), before)
  assert.equal(fs.statSync(path.join(repo, PAGE)).mtimeMs, 0, 'not rewritten')
  assert.ok(JSON.parse(sdlc(repo, ['ready', '--json']).stdout).length, 'still approved')
})

test('an approval whose file list lacks approval.md (an older approval) is not made stale by the page', () => {
  cleanChart(); ask(['Yes: the client said works means works.']); assert.equal(approve().code, 0)
  const f = path.join(repo, `${S}/approval.json`), row = JSON.parse(fs.readFileSync(f, 'utf8'))
  // an old row: no page in its files, and a digest computed without it
  fs.rmSync(path.join(repo, PAGE)); fs.writeFileSync(f, JSON.stringify({ ...row, files: row.files.filter((x: { path: string }) => x.path !== PAGE) }))
  assert.match(sdlc(repo, ['chart', 'report', '1']).stdout, /chart-1: approved/)
  fs.writeFileSync(path.join(repo, PAGE), 'anything\n')
  assert.match(sdlc(repo, ['chart', 'report', '1']).stdout, /chart-1: approved/, 'a page the row does not list is not hashed')
})

test('editing approval.md, or a file that feeds it, makes the approval stale', () => {
  cleanChart(); ask(['A real answer, long enough.']); assert.equal(approve().code, 0)
  const state = (): string => (JSON.parse(sdlc(repo, ['ready', '--json']).stdout) as unknown[]).length ? 'ready' : 'blocked'
  assert.equal(state(), 'ready')
  fs.appendFileSync(path.join(repo, PAGE), 'edited by hand\n')
  assert.equal(state(), 'blocked')
  assert.match(sdlc(repo, ['chart', 'report', '1']).stdout, /chart-1: stale/)
})

test('approval.md is protected from the model\'s Write and Edit, and may still be read', () => {
  fixture()
  const denied = (tool: string, input: object): string | null => { const o = hook(repo, 'holdout-guard', { tool_name: tool, tool_input: input }).stdout; return o ? JSON.parse(o).hookSpecificOutput.permissionDecision : null }
  for (const tool of ['Write', 'Edit', 'MultiEdit']) assert.equal(denied(tool, { file_path: path.join(repo, PAGE) }), 'deny', tool)
  assert.equal(denied('Write', { file_path: path.join(repo, `${S}/prd.md`) }), null)
  assert.equal(denied('Read', { file_path: path.join(repo, PAGE) }), null)
})
