// What a change leaves for later (sprint 1 run findings, 2026-10-28): its open review items go to the unbuilt intent that owns them,
// else the backlog; the behaviours and amendments it added are recorded in its own intent. Routing only places an item, it never fixes or drops one.
// Both generated sections sit outside the chart approval (chart.ts hashes the intent without them).
import fs from 'node:fs'
import path from 'node:path'
import { ROOT, CHANGES, toPosix, exists, read, out, fail, checkSlug, type Args } from './core.ts'
import { section, matchesAny } from './model.ts'
import { intentOf, intentsOf } from './chart.ts'
import { isShipped, changeDir } from './lifecycle.ts'
import { PRODUCT, intentRel } from './product.ts'

export type ReviewItem = { section: 'Deferred' | 'Unverifiable'; text: string; file: string | null; carry: string | null }
const MARK = '<!-- generated by sdlc pr; outside the chart approval -->'
const BACKLOG = path.join(PRODUCT, 'backlog.md')
const NONE = /^(none|nothing|n\/a|no deferred items?|no findings?)\.?$/i
const RESOLVED = /→\s*(?:fixed|waived|dropped|carried|taken)\b/i
const CARRY = /\s*→\s*carry:\s*([\w.-]+)/

// The marker sits right under the heading (an older run put it above it: both forms are stripped).
export const stripGenerated = (t: string): string => t.replace(/\n<!-- generated by sdlc pr[^\n]*-->\n^## (?:Carried in|Added during the change)[ \t]*\n[\s\S]*?(?=\n<!-- generated by sdlc pr|^## |(?![\s\S]))/gm, '').replace(/\n^## Added during the change[ \t]*\n<!-- generated by sdlc pr[^\n]*-->\n[\s\S]*?(?=^## |(?![\s\S]))/gm, '')
// Carried items live beside the intent, not in it, so two changes shipping in parallel never edit the same file.
export const carriedFile = (intentFile: string): string => path.join(path.dirname(path.dirname(intentFile)), 'carried', path.basename(intentFile))
export const carriedIds = (intentFile: string): string[] => [...read(carriedFile(intentFile)).matchAll(/^\s*[-*]\s+(C\d+)\b/gm)].map(m => m[1]!)

// The path or path:line token before any resolution arrow: a slash path with an extension or on disk first (not and/or), then one that exists, then any.
function fileOf(text: string): string | null {
  const ts = (text.split(/\s→\s/)[0] ?? '').split(/\s+/).map(raw => raw.replace(/[`'"]/g, '').replace(/^\(/, '').replace(/[,;.)]+$/, '').replace(/:$/, '').replace(/:\d+(?:[-:]\d+)?$/, ''))
    .filter(t => /^[\w@.\-/]+$/.test(t) && (t.includes('/') || /\.[A-Za-z]\w{0,4}$/.test(t)) && !/^(e\.g|i\.e)$/i.test(t))
  const real = (t: string): boolean => /\.[A-Za-z]\w{0,4}$/.test(t) || exists(path.join(ROOT, t))
  return ts.find(t => t.includes('/') && real(t)) ?? ts.find(t => exists(path.join(ROOT, t))) ?? ts.find(t => t.includes('/')) ?? ts[0] ?? null
}
export function reviewItems(review: string): ReviewItem[] {
  const BUL = /^(?:[-*]|\d+[.)])\s+/
  return (['Deferred', 'Unverifiable'] as const).flatMap(s => (new RegExp(`^#{2,3}[ \\t]+${s}\\b[^\\n]*\\n([\\s\\S]*?)(?=^#{2,3}[ \\t]|(?![\\s\\S]))`, 'm').exec(review)?.[1] ?? '').split(/\n(?=(?:[-*]|\d+[.)])\s)/).map(c => c.trim()).filter(c => BUL.test(c)).flatMap(c => {
    const raw = c.replace(BUL, '').replace(/\s*\n\s*/g, ' ').trim()
    if (!raw || NONE.test(raw) || RESOLVED.test(raw)) return []
    return [{ section: s, text: raw.replace(CARRY, '').trim(), file: fileOf(raw), carry: CARRY.exec(raw)?.[1] ?? null }]
  }))
}

// Appends a line to a generated section of a file, creating the section (with its marker) at the end.
function append(file: string, heading: string, line: string): void {
  const t = read(file), at = new RegExp(`^## ${heading}[ \\t]*\\n`, 'm').exec(t)
  if (!at) return void fs.writeFileSync(file, `${t}\n## ${heading}\n${MARK}\n${line}\n`) // t kept byte for byte: the chart hash strips only the section
  const from = at.index + at[0].length, rest = t.slice(from), m = /\n<!-- generated by sdlc pr|^## /m.exec(rest), end = from + (m ? m.index : rest.length)
  const after = t.slice(end)
  fs.writeFileSync(file, `${t.slice(0, end).replace(/\s*$/, '\n')}${line}\n${after && !after.startsWith('\n') ? '\n' : ''}${after}`)
}
const nextId = (text: string, re: RegExp): number => Math.max(0, ...[...text.matchAll(re)].map(m => Number(m[1]))) + 1
const owns = (entry: string, file: string): boolean => entry === file || file.startsWith(entry.endsWith('/') ? entry : `${entry}/`) || matchesAny(file, [entry])

export function routeReview(slug: string): { carried: Record<string, string[]>; backlog: string[]; files: string[] } {
  const res = { carried: {} as Record<string, string[]>, backlog: [] as string[], files: [] as string[] }
  const items = reviewItems(read(path.join(CHANGES, slug, 'review.md')))
  if (!items.length) return res
  const n = intentOf(slug)?.sprint ?? null
  const sprint = typeof n === 'number' ? intentsOf(n) : []
  const open = sprint.filter(i => i.slug !== slug && !isShipped(i.slug) && !exists(changeDir(i.slug)))
  const seen = [read(BACKLOG), ...sprint.flatMap(i => [read(i.file), read(carriedFile(i.file))])].join('\n')
  for (const it of items) {
    if (seen.includes(`(from ${slug} review): ${it.text}`) || seen.includes(`(${slug}, sprint ${n ?? '-'}): ${it.text}`)) continue
    const to = open.find(i => i.slug === it.carry) ?? open.find(i => it.file && i.scope.some(s => owns(s, it.file!)))
    if (to) {
      const cf = carriedFile(to.file), t = exists(cf) ? read(cf) : `# Carried into ${to.slug}\n${MARK}\n`, line = `- C${nextId(t, /\bC(\d+)\b/g)} (from ${slug} review): ${it.text}`
      fs.mkdirSync(path.dirname(cf), { recursive: true }); fs.writeFileSync(cf, `${t.replace(/\s*$/, '\n')}${line}\n`)
      ;(res.carried[to.slug] ??= []).push(line); res.files.push(toPosix(path.relative(ROOT, cf)))
    } else {
      const text = exists(BACKLOG) ? read(BACKLOG) : `# Backlog\n\n<!-- generated by sdlc pr: review items no unbuilt intent owns; /rig-chart asks each [open] one at its gap pass -->\n`
      const line = `- [open] BL-${nextId(text, /\bBL-(\d+)\b/g)} (${slug}, sprint ${n ?? '-'}): ${it.text}`
      fs.mkdirSync(PRODUCT, { recursive: true })
      fs.writeFileSync(BACKLOG, `${text.replace(/\s*$/, '\n')}${line}\n`); res.backlog.push(line); res.files.push(toPosix(path.relative(ROOT, BACKLOG)))
    }
  }
  // A rerun after a rolled-back commit finds its lines already written: it still names those files, or the PR would ship without them.
  const mine = [BACKLOG, ...sprint.map(i => carriedFile(i.file))].filter(f => exists(f) && (read(f).includes(`(from ${slug} review): `) || read(f).includes(`(${slug}, sprint `)))
  res.files = [...new Set([...res.files, ...mine.map(f => toPosix(path.relative(ROOT, f)))])]
  return res
}

// Behaviours the intent never named, and the change's amendments, in the intent they came from; each once.
export function recordAdditions(slug: string): { added: string[]; files: string[] } {
  const n = intentOf(slug)?.sprint
  if (typeof n !== 'number') return { added: [], files: [] }
  const file = path.join(ROOT, intentRel(n, slug)), have = read(file), own = stripGenerated(have), done = section(have, 'Added during the change')
  const spec = section(read(path.join(CHANGES, slug, 'spec.md')), 'Behaviours').split('\n').filter(l => { const id = /^\s*[-*]\s+(B\d+)\b/.exec(l)?.[1]; return id && !new RegExp(`\\b${id}\\b`).test(own) })
  const am = read(path.join(CHANGES, slug, 'amendments.md')).split('\n').filter(l => /^\s*[-*]\s+A\d+\b/.test(l))
  const added = [...spec, ...am].map(l => l.trim()).filter(l => !done.includes(l))
  for (const l of added) append(file, 'Added during the change', l)
  return { added, files: added.length || done.trim() ? [intentRel(n, slug)] : [] }
}

// `carry <slug>`: the same routing for a change that shipped before this existed.
export function cmdCarry(args: Args): void {
  const slug = checkSlug(args.pos[0] ?? '')
  if (!exists(path.join(CHANGES, slug, 'intent.md'))) fail(`${slug} has no intent.md`)
  const r = routeReview(slug), { added } = recordAdditions(slug)
  const lines = [...Object.entries(r.carried).flatMap(([to, ls]) => ls.map(l => `carried to ${to}: ${l}`)), ...r.backlog.map(l => `backlog: ${l}`), ...added.map(l => `added to ${slug}: ${l}`)]
  out(lines.length ? `${lines.join('\n')}\ncommit the result` : `${slug}: nothing to carry`)
}
