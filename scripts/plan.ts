// The sprint plan view (`chart plan <N>`): a read-only picture of the order the sprint's intents can be built in, generated from their
// `depends:` lines so it cannot disagree with them. Waves, an ASCII tree for the terminal, a Mermaid graph for GitHub, and what can start now.
import { skillRef } from './core.ts'
type PlanStatus = 'done' | 'active' | 'ready' | 'blocked'
export type PlanRow = { slug: string; depends: string[]; estimateDays: number | null; status: PlanStatus }

const ICON: Record<PlanStatus, string> = { done: '✔', active: '▶', ready: '○', blocked: '✖' }

// Wave 1 has no dependency inside the sprint; any other intent is one wave after its latest in-sprint dependency. A dependency on another
// sprint's intent is already decided by its status, so it does not push the wave. Cycles are a chart-check finding; here they get wave 1.
export function waves(rows: PlanRow[]): Map<string, number> {
  const by = new Map(rows.map(r => [r.slug, r]))
  const wave = new Map<string, number>()
  const of = (slug: string, path: string[]): number => {
    const known = wave.get(slug)
    if (known !== undefined) return known
    if (path.includes(slug)) return 1
    const deps = (by.get(slug)?.depends ?? []).filter(d => by.has(d))
    const w = deps.length ? 1 + Math.max(...deps.map(d => of(d, [...path, slug]))) : 1
    wave.set(slug, w)
    return w
  }
  for (const r of [...rows].sort((a, b) => a.slug.localeCompare(b.slug))) of(r.slug, [])
  return wave
}

const label = (r: PlanRow): string => `${r.slug} ${ICON[r.status]} ${r.status}`
const sorted = (rows: PlanRow[], wave: Map<string, number>): PlanRow[] => [...rows].sort((a, b) => (wave.get(a.slug) ?? 1) - (wave.get(b.slug) ?? 1) || a.slug.localeCompare(b.slug))

// A tree of the DAG: each intent hangs under its latest in-sprint dependency, and names its other dependencies in "(also after: ...)", so
// every intent is printed once.
function asciiTree(rows: PlanRow[]): string {
  const wave = waves(rows)
  const by = new Map(rows.map(r => [r.slug, r]))
  const inSprint = (r: PlanRow): string[] => r.depends.filter(d => by.has(d))
  const parentOf = (r: PlanRow): string | undefined => [...inSprint(r)].sort((a, b) => (wave.get(b) ?? 1) - (wave.get(a) ?? 1) || a.localeCompare(b))[0]
  const kids = (slug: string | undefined): PlanRow[] => sorted(rows.filter(r => parentOf(r) === slug), wave)
  const note = (r: PlanRow): string => {
    const others = r.depends.filter(d => d !== parentOf(r))
    return others.length ? `  (also after: ${others.join(', ')})` : ''
  }
  const lines: string[] = []
  const walk = (r: PlanRow, prefix: string, last: boolean, root: boolean): void => {
    lines.push(`${root ? '' : prefix + (last ? '└─ ' : '├─ ')}${label(r)}${note(r)}`)
    const next = root ? '' : prefix + (last ? '   ' : '│  ')
    const children = kids(r.slug)
    children.forEach((c, i) => walk(c, next, i === children.length - 1, false))
  }
  for (const r of kids(undefined)) walk(r, '', true, true)
  // An intent on (or hanging off) a dependency cycle has no root above it: list it so no intent is missing from the picture.
  const shown = new Set(lines.map(l => /([a-z0-9-]+) [✔▶○✖]/.exec(l)?.[1]))
  for (const r of sorted(rows.filter(x => !shown.has(x.slug)), wave)) lines.push(`${label(r)}  (on a dependency cycle, or after one: depends on ${r.depends.join(', ')})`)
  return lines.join('\n')
}

export function mermaid(rows: PlanRow[]): string {
  const id = (s: string): string => `n_${s.replace(/[^a-zA-Z0-9]/g, '_')}` // a bare `end` is a Mermaid keyword
  const by = new Set(rows.map(r => r.slug))
  return [
    'graph LR',
    ...rows.map(r => `  ${id(r.slug)}["${r.slug}"]:::${r.status}`),
    ...rows.flatMap(r => r.depends.filter(d => by.has(d)).map(d => `  ${id(d)} --> ${id(r.slug)}`)),
    '  classDef done fill:#d4edda,stroke:#2e7d32',
    '  classDef active fill:#fff3cd,stroke:#b8860b',
    '  classDef ready fill:#cce5ff,stroke:#1565c0',
    '  classDef blocked fill:#f8d7da,stroke:#c62828',
  ].join('\n')
}

export function planText(n: number, rows: PlanRow[], opts: { chart: string; startCmd: (slug: string) => string }): string {
  if (!rows.length) return `# Sprint ${n} plan\n\nThis sprint has no intents yet.\n`
  const wave = waves(rows)
  const days = rows.reduce((s, r) => s + (r.estimateDays ?? 0), 0)
  const ready = sorted(rows.filter(r => r.status === 'ready'), wave)
  const blockers = (r: PlanRow): string => r.depends.join(', ') || '-'
  return [
    `# Sprint ${n} plan`,
    '',
    '<!-- Generated by `chart plan` from the intents\' `depends:` lines. Do not edit: change an intent and regenerate. -->',
    '',
    `${rows.length} intents, ${days} engineer-day(s), ${Math.max(...wave.values())} wave(s). Chart: ${opts.chart}. Intents in the same wave can be built in parallel.`,
    '',
    '## Waves',
    '',
    '| Wave | Intent | Depends on | Days | Status |',
    '|---|---|---|---|---|',
    ...sorted(rows, wave).map(r => `| ${wave.get(r.slug)} | ${r.slug} | ${blockers(r)} | ${r.estimateDays ?? '?'} | ${r.status} |`),
    '',
    '## Graph (text)',
    '',
    '```text',
    asciiTree(rows),
    '```',
    '',
    `Key: ${(Object.keys(ICON) as PlanStatus[]).map(s => `${ICON[s]} ${s}`).join(', ')}. An arrow-free tree: each intent sits under its latest dependency.`,
    '',
    '## Graph (Mermaid)',
    '',
    '```mermaid',
    mermaid(rows),
    '```',
    '',
    '## Next up',
    '',
    ...(opts.chart !== 'approved' ? [`- chart-${n} is ${opts.chart}: a person runs \`${skillRef('approve')} chart-${n}\` before anything can start`] : []),
    ...(ready.length ? ready.map(r => `- \`${opts.startCmd(r.slug)}\``) : ['- nothing can start now (everything is done, in progress or blocked)']),
    '',
  ].join('\n')
}
